#!/usr/bin/env python3
"""Generate the How It Works guide pages and their sitemap entries.

Run after adding, removing or renaming a guide, or changing a guide's title or
summary, in assets/guides.js:

    python3 scripts/build_guide_pages.py

It writes /<lang>/how-to/<slug>.html (a static shell with metadata; the page
content is rendered by assets/site.js from assets/guides.js), makes sure the
How It Works pages load guides.js, and rewrites the guide block in sitemap.xml.
No dependencies beyond the Python standard library.
"""

from __future__ import annotations

import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = "https://jaxmaxdelta.com"
LANGS = ("en", "fr", "es")
LOCALES = {"en": "en_US", "fr": "fr_CA", "es": "es_ES"}
NOSCRIPT = {
    "en": "Jax Max Delta needs JavaScript to display this page.",
    "fr": "Jax Max Delta a besoin de JavaScript pour afficher cette page.",
    "es": "Jax Max Delta necesita JavaScript para mostrar esta página.",
}
BACK = {"en": "How It Works", "fr": "Fonctionnement", "es": "Cómo funciona"}
SITEMAP_START = "  <!-- guides:start (generated by scripts/build_guide_pages.py) -->\n"
SITEMAP_END = "  <!-- guides:end -->\n"


def read_guides() -> tuple[list[str], dict[str, dict[str, tuple[str, str]]]]:
    source = (ROOT / "assets" / "guides.js").read_text(encoding="utf-8")
    order = re.findall(r'"([a-z-]+)"', re.search(r"GUIDE_ORDER = \[([^\]]*)\]", source).group(1))
    starts = {lang: source.index(f"\n  {lang}: {{") for lang in LANGS}
    bounds = sorted(starts.values()) + [len(source)]
    guides: dict[str, dict[str, tuple[str, str]]] = {}
    for lang, start in starts.items():
        block = source[start : bounds[bounds.index(start) + 1]]
        items = re.findall(
            r'^      "?([a-z-]+)"?: \{\n        title: "((?:[^"\\]|\\.)*)",\n        summary: "((?:[^"\\]|\\.)*)",',
            block,
            re.M,
        )
        guides[lang] = {slug: (unescape_js(title), unescape_js(summary)) for slug, title, summary in items}
        missing = [slug for slug in order if slug not in guides[lang]]
        if missing:
            raise SystemExit(f"{lang}: guides missing from assets/guides.js: {missing}")
    return order, guides


def unescape_js(value: str) -> str:
    return re.sub(r"<[^>]+>", "", value.replace('\\"', '"').replace("\\u201c", "“").replace("\\u201d", "”"))


def attr(value: str) -> str:
    return html.escape(value, quote=True)


def page(lang: str, slug: str, title: str, summary: str) -> str:
    url = f"{BASE}/{lang}/how-to/{slug}.html"
    full_title = attr(f"{title} — Jax Max Delta")
    desc = attr(summary)
    alternates = "\n".join(
        f'  <link rel="alternate" hreflang="{code}" href="{BASE}/{code}/how-to/{slug}.html">' for code in LANGS
    )
    locale_alts = "\n".join(
        f'  <meta property="og:locale:alternate" content="{LOCALES[code]}">' for code in LANGS if code != lang
    )
    return f"""<!doctype html>
<html lang="{lang}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{full_title}</title>
  <meta name="description" content="{desc}">
  <meta name="author" content="Camilore Inc.">
  <meta name="publisher" content="Camilore Inc.">
  <meta name="theme-color" content="#07080b">
  <link rel="canonical" href="{url}">
{alternates}
  <link rel="alternate" hreflang="x-default" href="{BASE}/en/how-to/{slug}.html">
  <meta property="og:type" content="article">
  <meta property="og:site_name" content="Jax Max Delta">
  <meta property="og:locale" content="{LOCALES[lang]}">
{locale_alts}
  <meta property="og:url" content="{url}">
  <meta property="og:title" content="{full_title}">
  <meta property="og:description" content="{desc}">
  <meta property="og:image" content="{BASE}/assets/brand/jmd-og-1200x630.png">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta property="og:image:alt" content="Jax Max Delta — Your race engineer. Your pit wall. Your race memory.">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="{full_title}">
  <meta name="twitter:description" content="{desc}">
  <meta name="twitter:image" content="{BASE}/assets/brand/jmd-og-1200x630.png">
  <link rel="icon" href="../../favicon.png" type="image/png" sizes="32x32">
  <link rel="apple-touch-icon" href="../../apple-touch-icon.png">
  <link rel="stylesheet" href="../../assets/site.css">
  <script src="../../assets/guides.js" defer></script>
  <script src="../../assets/site.js" defer></script>
</head>
<body data-page="guide" data-slug="{slug}">
  <div id="app"><noscript><p>{NOSCRIPT[lang]}</p><p><a href="../how-to.html">{BACK[lang]}</a> · {html.escape(summary)}</p></noscript></div>
</body>
</html>
"""


def sitemap_block(order: list[str]) -> str:
    entries = []
    for slug in order:
        links = "".join(
            f'    <xhtml:link rel="alternate" hreflang="{code}" href="{BASE}/{code}/how-to/{slug}.html"/>\n' for code in LANGS
        )
        links += f'    <xhtml:link rel="alternate" hreflang="x-default" href="{BASE}/en/how-to/{slug}.html"/>\n'
        for lang in LANGS:
            entries.append(f"  <url>\n    <loc>{BASE}/{lang}/how-to/{slug}.html</loc>\n{links}  </url>\n")
    return SITEMAP_START + "".join(entries) + SITEMAP_END


def main() -> None:
    order, guides = read_guides()
    for lang in LANGS:
        folder = ROOT / lang / "how-to"
        folder.mkdir(exist_ok=True)
        for stale in folder.glob("*.html"):
            if stale.stem not in order:
                stale.unlink()
        for slug in order:
            title, summary = guides[lang][slug]
            (folder / f"{slug}.html").write_text(page(lang, slug, title, summary), encoding="utf-8")

        how = ROOT / lang / "how-to.html"
        text = how.read_text(encoding="utf-8")
        tag = '  <script src="../assets/guides.js" defer></script>\n'
        if tag not in text:
            text = text.replace('  <script src="../assets/site.js" defer></script>\n', tag + '  <script src="../assets/site.js" defer></script>\n')
            how.write_text(text, encoding="utf-8")

    sitemap_path = ROOT / "sitemap.xml"
    sitemap = sitemap_path.read_text(encoding="utf-8")
    if SITEMAP_START in sitemap:
        sitemap = sitemap[: sitemap.index(SITEMAP_START)] + sitemap[sitemap.index(SITEMAP_END) + len(SITEMAP_END) :]
    sitemap = sitemap.replace("</urlset>", sitemap_block(order) + "</urlset>")
    sitemap_path.write_text(sitemap, encoding="utf-8")
    print(f"Wrote {len(order) * len(LANGS)} guide pages and their sitemap entries.")


if __name__ == "__main__":
    main()
